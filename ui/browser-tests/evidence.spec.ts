import { expect, test } from '@playwright/test';
test('actual snapshot, filters, invalid import and narrow layout', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto('/');
  await expect(page.locator('#cases tr')).toHaveCount(13);
  await expect(page.locator('#metrics')).toContainText('53.8%');
  await expect(page.locator('#comparison-rows tr')).toHaveCount(3);
  await expect(page.locator('#comparison-rows')).toContainText('9/13');
  await expect(page.locator('#comparison-rows')).toContainText('LiquidAI/d1-3B');
  await expect(page.locator('#intent-rows tr')).toHaveCount(5);
  await expect(page.locator('#intent-rows')).toContainText('15/21');
  await expect(page.locator('#intent-rows')).toContainText('multinomial_naive_bayes_cpu');
  await expect(page.getByText('Saved snapshot · not live')).toBeVisible();
  await page.getByRole('button', { name: 'Needs review' }).click();
  await expect(page.locator('#cases tr')).toHaveCount(6);
  await page.getByRole('button', { name: 'Matched', exact: true }).click();
  await expect(page.locator('#cases tr')).toHaveCount(7);
  await page.getByRole('button', { name: 'All decisions' }).click();
  await page.screenshot({ path: '../.swag/evidence/20261028/swag-panel-desktop.png', fullPage: true });
  await page.locator('#import').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"schemaVersion":99}') });
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.locator('#cases tr')).toHaveCount(13);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await expect(page.locator('#cases tr')).toHaveCount(13);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: '../.swag/evidence/20261028/swag-panel-mobile.png', fullPage: true });
  expect(errors).toEqual([]);
});
